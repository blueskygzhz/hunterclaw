状态说明:

• DISCONNECTED (断开)
  - 初始状态
  - 触发: start() → CONNECTING

• CONNECTING (连接中)
  - 正在建立连接
  - 成功 → CONNECTED
  - 失败 → RECONNECTING

• CONNECTED (已连接)
  - 正常工作状态
  - 定期发送心跳 (每 5 秒)
  - 连续 3 次心跳超时 → RECONNECTING

• RECONNECTING (重连中)
  - 指数退避等待
  - 尝试次数 < max → CONNECTING
  - 尝试次数 >= max → FAILED

• FAILED (失败)
  - 最终失败状态
  - 停止监控


