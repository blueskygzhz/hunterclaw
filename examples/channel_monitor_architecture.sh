4️⃣ 自动重连策略 (指数退避)
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

指数退避算法:

    delay = base_delay × 2^(attempt - 1)
    delay = min(delay, max_delay)

