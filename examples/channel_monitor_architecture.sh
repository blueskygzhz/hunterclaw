并发特性:

• 独立线程
  ├── 每个通道一个监控线程
  ├── 线程间完全隔离
  └── 避免互相干扰

• 资源隔离
  ├── 独立的健康指标
  ├── 独立的重连策略
  └── 独立的事件队列

• 统一管理
  ├── start_all() / stop_all()
  ├── 聚合健康报告
  └── 全局事件处理

