心跳流程:

1. 发送心跳 (send_heartbeat)
   ├── heartbeat_sent++
   └── 记录发送时间

2. 等待响应 (最多 10 秒)
   ├── 成功: heartbeat_received++
   └── 失败: heartbeat_timeout++

3. 判断健康状态
   ├── timeout < 3: 继续监控
   └── timeout >= 3: 触发重连


